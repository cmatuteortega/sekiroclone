function Font.width(text)
    return #text * ADVANCE - 1
end

-- Plotted with the colour already set by the caller.
function Font.print(text, x, y)
    text = text:upper()
    for n = 1, #text do
        local g = GLYPHS[text:sub(n, n)]
        if g then
            for r = 1, GH do
                local row = g[r]
                for c = 1, GW do
                    if row:sub(c, c) == "#" then
                        love.graphics.rectangle("fill", x + (n - 1) * ADVANCE + c - 1, y + r - 1, 1, 1)
                    end
                end
            end
        end
    end
end

return Font
